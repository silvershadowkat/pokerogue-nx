// Generate the native adapter from the same UI hit regions used by the WebView
// baseline. No game rules, state editing, or save formats are duplicated here.
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const root = path.resolve(__dirname, '..');
const adapter = fs.readFileSync(path.join(root, 'src/handheld/handheld.ts'), 'utf8')
  .split('export function installHandheld')[0].replace(/^import .*;\r?\n/gm, '');
const enums = ['buttons', 'ui-mode'].map(name => fs.readFileSync(path.join(root, `src/enums/${name}.ts`), 'utf8').replace('export enum', 'enum')).join('\n');
const touch = `
let globalScene:any;
${enums}
${adapter}
let attached=false, down:any=null;
__rt.frameHooks.push(()=>{
  if(attached)return;
  const game=__rt.renderer?.game;
  const scene=game?.scene.getScene('battle');
  if(!scene?.ui)return;
  globalScene=scene;attached=true;
  const canvas=game.canvas;
  // gl.c centers and fits the framebuffer independently of CSS layout.
  const point=(e:any)=>{
    const size=__native.screenSize();
    const scale=Math.min(size.width/canvas.width,size.height/canvas.height);
    return {x:(e.clientX-(size.width-canvas.width*scale)/2)/scale,
      y:(e.clientY-(size.height-canvas.height*scale)/2)/scale};
  };
  canvas.addEventListener('pointerdown',(e:any)=>{down={...point(e),mode:scene.ui.mode};});
  canvas.addEventListener('pointercancel',()=>{down=null;});
  canvas.addEventListener('pointerup',(e:any)=>{
    if(!down)return;
    const p=point(e),start=down;down=null;
    if(start.mode!==scene.ui.mode)return;
    const dx=p.x-start.x,dy=p.y-start.y;
    if(Math.hypot(dx,dy)>70){send(Math.abs(dx)>Math.abs(dy)?(dx>0?Button.LEFT:Button.RIGHT):(dy>0?Button.UP:Button.DOWN));return;}
    const handler=scene.ui.getHandler();
    if(handler?.tutorialActive){scene.ui.processInput(Button.ACTION);return;}
    const hit=regions().find(r=>p.x>=r.x&&p.x<=r.x+r.w&&p.y>=r.y&&p.y<=r.y+r.h);
    if(hit){if(__native.logging)__native.log('[touch] '+hit.label);hit.run();return;}
    if([UiMode.MESSAGE,UiMode.EVOLUTION_SCENE,UiMode.EGG_HATCH_SCENE].includes(scene.ui.mode))send(Button.ACTION);
  });
  __native.log('[touch] direct UI selection ready');
});`;
const result=ts.transpileModule(touch,{compilerOptions:{target:ts.ScriptTarget.ES2020,module:ts.ModuleKind.None}});
const output=process.argv[2];
if(!output)throw new Error('Pass the runtime/js/handheld-touch.js output path');
fs.writeFileSync(output,'// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by handheld/build-native-touch.cjs; regenerate after UI changes.\n(function(){\n'+result.outputText+'\n})();\n');
console.log(output);
